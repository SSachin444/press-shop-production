-- Migrate distinct tool numbers already used in historical production_records without creating dummy data
insert into public.tools (tool_number, part_name, compatible_type, standard_uph, status)
select distinct
    upper(trim(pr.tool_number)) as tool_number,
    '' as part_name,
    case
        when bool_or(pr.production_type = 'Tandem') and bool_or(pr.production_type = 'NC') then 'Both'
        when bool_or(pr.production_type = 'Tandem') then 'Tandem'
        else 'NC'
    end as compatible_type,
    coalesce(max(nullif(pr.uph, 0)), 0) as standard_uph,
    'Active' as status
from public.production_records pr
where pr.tool_number is not null and trim(pr.tool_number) <> ''
group by upper(trim(pr.tool_number))
on conflict (tool_number) do nothing;

