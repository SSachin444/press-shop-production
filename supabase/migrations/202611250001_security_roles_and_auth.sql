-- 1. Authenticated User Profiles (Admin & Supervisor)
create table if not exists public.user_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text unique not null,
    full_name text not null,
    role text not null check (role in ('Admin', 'Supervisor')),
    department text not null default 'Press Shop MFG-2',
    recovery_email text default '',
    recovery_email_verified boolean not null default false,
    recovery_verify_code_hash text default '',
    recovery_verify_expires_at timestamp with time zone,
    must_change_password boolean not null default true,
    is_active boolean not null default true,
    last_login_at timestamp with time zone,
    created_at timestamp with time zone not null default timezone('utc'::text, now()),
    updated_at timestamp with time zone not null default timezone('utc'::text, now())
);

create index if not exists idx_user_profiles_role on public.user_profiles(role);
create index if not exists idx_user_profiles_username on public.user_profiles(username);

-- 2. Short-lived Single-Use Password Recovery Tokens
create table if not exists public.password_recovery_tokens (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.user_profiles(id) on delete cascade,
    target_role text not null check (target_role in ('Admin', 'Supervisor')),
    email text not null,
    code_hash text not null,
    expires_at timestamp with time zone not null,
    used_at timestamp with time zone,
    attempt_count integer not null default 0,
    requested_ip text default '',
    created_at timestamp with time zone not null default timezone('utc'::text, now())
);

create index if not exists idx_recovery_tokens_user_created
    on public.password_recovery_tokens(user_id, created_at desc);

-- 3. Recovery & Authentication Security Audit Log
create table if not exists public.recovery_audit_logs (
    id bigint generated by default as identity primary key,
    target_role text default '',
    email text default '',
    event_type text not null,
    success boolean not null default false,
    detail text default '',
    ip_address text default '',
    created_at timestamp with time zone not null default timezone('utc'::text, now())
);

-- 4. Helper functions for RLS role evaluation (do NOT trust client-provided headers)
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (
      select up.role
      from public.user_profiles up
      where up.id = auth.uid()
        and up.is_active = true
      limit 1
    ),
    case
      when coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) = true then 'Operator'
      when auth.role() = 'authenticated' and (auth.jwt() -> 'app_metadata' ->> 'role') in ('Admin', 'Supervisor', 'Operator')
        then (auth.jwt() -> 'app_metadata' ->> 'role')
      else 'Dashboard'
    end
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_app_role() = 'Admin';
$$;

create or replace function public.is_supervisor_or_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_app_role() in ('Admin', 'Supervisor');
$$;

create or replace function public.is_operator_or_above()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_app_role() in ('Admin', 'Supervisor', 'Operator');
$$;
