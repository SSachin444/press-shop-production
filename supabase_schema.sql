    id integer primary key default 1,
    state_json jsonb not null default '{}'::jsonb,
    updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- Ensure initial row exists
insert into app_state (id, state_json)
values (1, '{}'::jsonb)
on conflict (id) do nothing;

-- 2. Employees table
create table if not exists employees (
    id bigint generated by default as identity primary key,
    emp_id text unique not null,
    name text not null,
    department text not null default 'Press Shop MFG-2',
    designation text not null default 'Operator',
    phone text default '',
    email text default '',
    joining_date text default '',
    shift text default 'Shift A',
    assigned_machine text default '',
    status text default 'Active' check (status in ('Active', 'Inactive')),
    basic_salary numeric default 0,
    hra numeric default 0,
    da numeric default 0,
    conveyance numeric default 0,
    special_allowance numeric default 0,
    pf_deduction numeric default 0,
    esi_deduction numeric default 0,
    tds_deduction numeric default 0,
    ot_hourly_rate numeric default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()),
    updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- 3. Daily Attendance table
create table if not exists attendance (
    id bigint generated by default as identity primary key,
    emp_id text not null,
    date text not null,
    shift text not null,
    status text not null check (status in ('Present', 'Absent', 'Leave', 'Half-day', 'On-Duty')),
    check_in_time text default '',
    check_out_time text default '',
    notes text default '',
    doc_url text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()),
    unique(emp_id, date, shift)
);

-- 4. Overtime records
create table if not exists overtime (
    id bigint generated by default as identity primary key,
    emp_id text not null,
    date text not null,
    shift text not null,
    regular_hours numeric default 8.0,
    ot_hours numeric not null default 0,
    reason text default '',
    approval_status text default 'Pending' check (approval_status in ('Pending', 'Approved', 'Rejected')),
    approved_by text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()),
    unique(emp_id, date, shift)
);

-- 5. Machines table (NC presses and Tandem lines)
create table if not exists machines (
    id bigint generated by default as identity primary key,
    machine_number text unique not null,
    machine_type text not null check (machine_type in ('NC', 'Tandem')),
    tonnage numeric default 0,
    production_target integer default 500,
    status text default 'Idle' check (status in ('Running', 'Idle', 'Maintenance', 'Breakdown')),
    assigned_operator text default '',
    assigned_shift text default 'Shift A',
    maintenance_notes text default '',
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 6. Production Records (Hourly & Standard entries)
create table if not exists production_records (
    id bigint generated by default as identity primary key,
    production_type text not null check (production_type in ('NC', 'Tandem')),
    machine_or_line text not null,
    date text not null,
    shift text not null check (shift in ('Shift A', 'Shift B', 'Shift C')),
    hour_interval text not null,
    operator_name text default '',
    supervisor_name text default '',
    tool_number text default '',
    tonnage numeric default 0,
    target_qty integer not null default 0,
    actual_qty integer not null default 0,
    good_qty integer not null default 0,
    rejected_qty integer not null default 0,
    downtime_minutes integer not null default 0,
    downtime_reason text default '',
    remarks text default '',
    uph numeric default 0,
    production_pct numeric default 0,
    hourly_output_pct numeric default 0,
    entry_time text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()),
    unique(machine_or_line, date, shift, hour_interval)
);

-- Migration for existing production_records table:
alter table production_records add column if not exists uph numeric default 0;
alter table production_records add column if not exists production_pct numeric default 0;
alter table production_records add column if not exists hourly_output_pct numeric default 0;
alter table production_records add column if not exists entry_time text default '';

-- 7. Shift Handovers table
create table if not exists shift_handovers (
    id bigint generated by default as identity primary key,
    date text not null,
    outgoing_shift text not null check (outgoing_shift in ('Shift A', 'Shift B', 'Shift C')),
    incoming_shift text not null check (incoming_shift in ('Shift A', 'Shift B', 'Shift C')),
    department_or_machine text not null default 'All Shopfloor',
    handover_notes text not null,
    production_status text default '',
    pending_work text default '',
    machine_problems text default '',
    downtime_info text default '',
    quality_issues text default '',
    follow_up_actions text default '',
    responsible_person text not null,
    completion_status text default 'Open' check (completion_status in ('Open', 'In-Progress', 'Resolved')),
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 8. Machine Tool Next Plans
create table if not exists machine_plans (
    id bigint generated by default as identity primary key,
    machine_number text not null,
    plan_index integer not null check (plan_index >= 1 and plan_index <= 5),
    tool_number text not null,
    plan_quantity integer not null default 0,
    part_name text default '',
    status text default 'Queued' check (status in ('Queued', 'In Setup', 'Ready', 'In Progress', 'Completed')),
    target_date text default '',
    target_shift text default '',
    remarks text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()),
    updated_at timestamp with time zone default timezone('utc'::text, now()),
    unique(machine_number, plan_index)
);

-- 9. Machine Downtime Records
create table if not exists machine_downtime (
    id bigint generated by default as identity primary key,
    machine_number text not null,
    machine_type text default 'NC',
    date text not null,
    shift text not null,
    start_time text default '',
    end_time text default '',
    duration_minutes integer default 0,
    reason text not null,
    category text default 'Mechanical',
    reported_by text default '',
    action_taken text default '',
    status text default 'Open' check (status in ('Open', 'In-Progress', 'Resolved')),
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 10. Activity Logs for Audit History
create table if not exists activity_logs (
    id bigint generated by default as identity primary key,
    user_name text not null,
    action text not null,
    record_type text not null,
    details text default '',
    ip_address text default '',
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 11. Application Settings table
create table if not exists app_settings (
    key text primary key,
    value text not null
);

-- 12. Configurable Downtime Reason Codes (Maximum 6 Codes)
create table if not exists downtime_codes (
    code text primary key,
    name text not null,
    description text default '',
    display_order integer default 0,
    is_active boolean default true,
    created_at timestamp with time zone default timezone('utc'::text, now()),
    updated_at timestamp with time zone default timezone('utc'::text, now())
);

